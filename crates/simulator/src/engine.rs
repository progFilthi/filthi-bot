//! Generic bar-by-bar backtest engine with ATR stops, trailing stops,
//! time exits and session filters.
//!
//! Execution model (deliberately pessimistic):
//!   * Signals are read from the close of bar `i-1` and filled at the open of
//!     bar `i`. No look-ahead.
//!   * When a bar's range touches both the stop and the target, the **stop** is
//!     assumed to fill first.
//!   * A freshly opened position is checked against the entry bar's range too,
//!     so a violent entry bar can stop us out immediately.
//!   * The spread is charged once per round trip.
//!   * Only one position is open at a time.

use xau_core::{Bar, Side};

use crate::strategy::atr;

/// Point size for XAUUSD.
pub const POINT: f64 = 0.01;
/// Ounces per lot for XAUUSD.
pub const CONTRACT: f64 = 100.0;

#[derive(Debug, Clone)]
pub struct EngineConfig {
    pub initial_deposit: f64,
    pub lots: f64,
    /// ATR period used for stop sizing.
    pub atr_period: usize,
    /// Stop distance as a multiple of ATR.
    pub sl_atr: f64,
    /// Target distance as a multiple of ATR (0 = no target, ride the trail).
    pub tp_atr: f64,
    /// Trailing stop distance in ATR units (0 = disabled).
    pub trail_atr: f64,
    /// Force-close a trade after this many bars (0 = disabled).
    pub max_hold_bars: usize,
    /// Close a position when the opposite signal appears.
    pub exit_on_opposite: bool,
    /// Only allow entries when the UTC hour is in this list (empty = all hours).
    pub allowed_hours: Vec<u32>,
    /// Force-close at the close of the last bar before a gap of at least this
    /// many minutes (`None` = disabled). The broker's daily break and the
    /// weekend both produce such gaps, so this models "flat before the day
    /// ends" without hard-coding a clock hour that DST moves around.
    pub flat_before_gap_min: Option<i64>,
    /// Spread cost in points per round trip.
    pub spread_pts: f64,
    /// Commission per lot per round trip, in account currency.
    pub commission_per_lot: f64,
    /// Kill-switch: halt when equity falls this percent below the start.
    pub max_drawdown_pct: f64,
}

impl Default for EngineConfig {
    fn default() -> Self {
        Self {
            initial_deposit: 25_000.0,
            lots: 0.1,
            atr_period: 14,
            sl_atr: 2.0,
            tp_atr: 4.0,
            trail_atr: 0.0,
            max_hold_bars: 0,
            exit_on_opposite: true,
            allowed_hours: Vec::new(),
            flat_before_gap_min: None,
            spread_pts: 20.0,
            commission_per_lot: 0.0,
            max_drawdown_pct: 100.0,
        }
    }
}

/// One completed round trip.
#[derive(Debug, Clone)]
pub struct Trade {
    pub entry_bar: usize,
    pub exit_bar: usize,
    pub side: Side,
    pub entry: f64,
    pub exit: f64,
    pub pnl: f64,
    pub bars_held: usize,
    pub reason: ExitReason,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExitReason {
    StopLoss,
    TakeProfit,
    Trail,
    TimeExit,
    /// Forced out at the session's flat hour, not because time ran out.
    SessionClose,
    OppositeSignal,
    EndOfData,
}

impl ExitReason {
    pub fn label(&self) -> &'static str {
        match self {
            Self::StopLoss => "SL",
            Self::TakeProfit => "TP",
            Self::Trail => "TRAIL",
            Self::TimeExit => "TIME",
            Self::SessionClose => "FLAT",
            Self::OppositeSignal => "FLIP",
            Self::EndOfData => "EOD",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Position {
    pub side: Side,
    pub entry: f64,
    pub entry_bar: usize,
    pub sl: f64,
    pub tp: f64,
    pub atr_at_entry: f64,
    pub best: f64,
    pub lots: f64,
    /// True once the trailing stop has moved the stop from its initial price.
    pub trailed: bool,
}

#[derive(Debug, Clone, Default)]
pub struct Metrics {
    pub trades: usize,
    pub wins: usize,
    pub losses: usize,
    pub total_pnl: f64,
    pub gross_profit: f64,
    pub gross_loss: f64,
    pub win_rate: f64,
    pub profit_factor: f64,
    pub expectancy: f64,
    pub avg_win: f64,
    pub avg_loss: f64,
    pub max_drawdown: f64,
    pub max_drawdown_pct: f64,
    pub sharpe: f64,
    pub return_pct: f64,
    pub final_equity: f64,
    pub max_losing_streak: usize,
    pub avg_bars_held: f64,
    pub sl_exits: usize,
    pub tp_exits: usize,
    pub trail_exits: usize,
    pub other_exits: usize,
    pub exposure_pct: f64,
}

#[derive(Debug, Clone)]
pub struct Report {
    pub metrics: Metrics,
    pub trades: Vec<Trade>,
    pub equity_curve: Vec<f64>,
    pub halted_early: bool,
}

/// Run a backtest.
///
/// `signals[i]` is the entry signal generated by the close of bar `i`; it is
/// filled at the open of bar `i + 1`.
pub fn backtest(bars: &[Bar], signals: &[Option<Side>], cfg: &EngineConfig) -> Report {
    let n = bars.len();
    let atrs = atr(bars, cfg.atr_period.max(1));
    let spread_cost = cfg.spread_pts * POINT * CONTRACT * cfg.lots
        + cfg.commission_per_lot * cfg.lots;

    let mut equity = cfg.initial_deposit;
    let mut equity_curve = Vec::with_capacity(n + 1);
    equity_curve.push(equity);
    let mut pos: Option<Position> = None;
    let mut trades: Vec<Trade> = Vec::new();
    let mut bars_in_market = 0usize;
    let mut halted = false;
    let floor = cfg.initial_deposit * (1.0 - cfg.max_drawdown_pct / 100.0);

    for i in 0..n {
        let bar = &bars[i];
        let mut closed_this_bar = false;

        // ---- 1. Manage an open position against this bar's range ----
        if let Some(p) = pos.as_ref() {
            bars_in_market += 1;
            let (hit_stop, hit_target) = match p.side {
                Side::Buy => (bar.low <= p.sl, p.tp > 0.0 && bar.high >= p.tp),
                Side::Sell => (bar.high >= p.sl, p.tp > 0.0 && bar.low <= p.tp),
            };

            let mut exit: Option<(f64, ExitReason)> = None;
            if hit_stop {
                // Pessimistic: stop fills before target when both are touched.
                // Distinguish the original stop from a stop that has trailed up
                // into profit, so the exit mix is reported honestly.
                let reason = if p.trailed {
                    ExitReason::Trail
                } else {
                    ExitReason::StopLoss
                };
                exit = Some((p.sl, reason));
            } else if hit_target {
                exit = Some((p.tp, ExitReason::TakeProfit));
            } else if cfg.max_hold_bars > 0 && i.saturating_sub(p.entry_bar) >= cfg.max_hold_bars {
                exit = Some((bar.close, ExitReason::TimeExit));
            } else if cfg.flat_before_gap_min.is_some_and(|gap| match bars.get(i + 1) {
                Some(next) => (next.ts - bar.ts) / 60 >= gap,
                None => true,
            }) {
                exit = Some((bar.close, ExitReason::SessionClose));
            } else if cfg.exit_on_opposite {
                // Signal at the previous close opposing our position.
                if let Some(sig) = signals.get(i.saturating_sub(1)).copied().flatten() {
                    if sig != p.side {
                        exit = Some((bar.open, ExitReason::OppositeSignal));
                    }
                }
            }

            if let Some((px, reason)) = exit {
                let dir = if p.side == Side::Buy { 1.0 } else { -1.0 };
                let gross = (px - p.entry) * dir * CONTRACT * p.lots;
                let pnl = gross - spread_cost;
                equity += pnl;
                trades.push(Trade {
                    entry_bar: p.entry_bar,
                    exit_bar: i,
                    side: p.side,
                    entry: p.entry,
                    exit: px,
                    pnl,
                    bars_held: i - p.entry_bar,
                    reason,
                });
                pos = None;
                closed_this_bar = true;
            } else {
                // ---- Trailing stop maintenance at the close ----
                if cfg.trail_atr > 0.0 && !atrs[i].is_nan() {
                    let dist = cfg.trail_atr * atrs[i];
                    if let Some(p) = pos.as_mut() {
                        p.best = match p.side {
                            Side::Buy => p.best.max(bar.high),
                            Side::Sell => p.best.min(bar.low),
                        };
                        match p.side {
                            Side::Buy => {
                                let cand = p.best - dist;
                                if cand > p.sl {
                                    p.sl = cand;
                                    p.trailed = true;
                                }
                            }
                            Side::Sell => {
                                let cand = p.best + dist;
                                if cand < p.sl {
                                    p.sl = cand;
                                    p.trailed = true;
                                }
                            }
                        }
                    }
                }
            }
        }

        // ---- 2. Enter on a signal from the previous bar ----
        if pos.is_none() && !closed_this_bar && i > 0 {
            if let Some(sig) = signals[i - 1] {
                let hour_ok = cfg.allowed_hours.is_empty()
                    || cfg
                        .allowed_hours
                        .contains(&(((bar.ts % 86_400) / 3_600) as u32));
                let a = atrs[i - 1];
                if hour_ok && !a.is_nan() && a > 0.0 {
                    let entry = bar.open;
                    let dir = if sig == Side::Buy { 1.0 } else { -1.0 };
                    let sl = entry - dir * cfg.sl_atr * a;
                    let tp = if cfg.tp_atr > 0.0 {
                        entry + dir * cfg.tp_atr * a
                    } else {
                        0.0
                    };
                    pos = Some(Position {
                        side: sig,
                        entry,
                        entry_bar: i,
                        sl,
                        tp,
                        atr_at_entry: a,
                        best: entry,
                        lots: cfg.lots,
                        trailed: false,
                    });
                }
            }
        }

        // ---- 3. Mark to market ----
        let open_pnl = pos.as_ref().map_or(0.0, |p| {
            let dir = if p.side == Side::Buy { 1.0 } else { -1.0 };
            (bar.close - p.entry) * dir * CONTRACT * p.lots - spread_cost
        });
        equity_curve.push(equity + open_pnl);

        if equity + open_pnl <= floor {
            halted = true;
            if let Some(p) = pos.take() {
                let dir = if p.side == Side::Buy { 1.0 } else { -1.0 };
                let pnl = (bar.close - p.entry) * dir * CONTRACT * p.lots - spread_cost;
                equity += pnl;
                trades.push(Trade {
                    entry_bar: p.entry_bar,
                    exit_bar: i,
                    side: p.side,
                    entry: p.entry,
                    exit: bar.close,
                    pnl,
                    bars_held: i - p.entry_bar,
                    reason: ExitReason::EndOfData,
                });
            }
            break;
        }
    }

    // ---- Force-close anything still open at the end of the data ----
    if let Some(p) = pos.take() {
        let bar = &bars[n - 1];
        let dir = if p.side == Side::Buy { 1.0 } else { -1.0 };
        let pnl = (bar.close - p.entry) * dir * CONTRACT * p.lots - spread_cost;
        equity += pnl;
        trades.push(Trade {
            entry_bar: p.entry_bar,
            exit_bar: n - 1,
            side: p.side,
            entry: p.entry,
            exit: bar.close,
            pnl,
            bars_held: (n - 1).saturating_sub(p.entry_bar),
            reason: ExitReason::EndOfData,
        });
    }

    while equity_curve.len() < n + 1 {
        equity_curve.push(equity);
    }

    let metrics = compute_metrics(bars, &trades, &equity_curve, cfg, bars_in_market, halted);
    Report {
        metrics,
        trades,
        equity_curve,
        halted_early: halted,
    }
}

fn compute_metrics(
    bars: &[Bar],
    trades: &[Trade],
    equity_curve: &[f64],
    cfg: &EngineConfig,
    bars_in_market: usize,
    halted: bool,
) -> Metrics {
    let mut m = Metrics {
        trades: trades.len(),
        ..Default::default()
    };
    for t in trades {
        m.total_pnl += t.pnl;
        if t.pnl > 0.0 {
            m.wins += 1;
            m.gross_profit += t.pnl;
        } else {
            m.losses += 1;
            m.gross_loss += t.pnl.abs();
        }
        match t.reason {
            ExitReason::StopLoss => m.sl_exits += 1,
            ExitReason::TakeProfit => m.tp_exits += 1,
            ExitReason::Trail => m.trail_exits += 1,
            _ => m.other_exits += 1,
        }
    }
    m.final_equity = cfg.initial_deposit + m.total_pnl;
    m.win_rate = if m.trades > 0 {
        m.wins as f64 / m.trades as f64 * 100.0
    } else {
        0.0
    };
    m.profit_factor = if m.gross_loss > 0.0 {
        m.gross_profit / m.gross_loss
    } else if m.gross_profit > 0.0 {
        f64::INFINITY
    } else {
        0.0
    };
    m.expectancy = if m.trades > 0 {
        m.total_pnl / m.trades as f64
    } else {
        0.0
    };
    m.avg_win = if m.wins > 0 { m.gross_profit / m.wins as f64 } else { 0.0 };
    m.avg_loss = if m.losses > 0 { -m.gross_loss / m.losses as f64 } else { 0.0 };
    m.return_pct = m.total_pnl / cfg.initial_deposit * 100.0;
    m.avg_bars_held = if m.trades > 0 {
        trades.iter().map(|t| t.bars_held as f64).sum::<f64>() / m.trades as f64
    } else {
        0.0
    };
    m.exposure_pct = if bars.is_empty() {
        0.0
    } else {
        bars_in_market as f64 / bars.len() as f64 * 100.0
    };

    // Max drawdown in dollars and percent.
    let mut peak = equity_curve[0];
    for &v in equity_curve {
        if v > peak {
            peak = v;
        }
        let dd = peak - v;
        if dd > m.max_drawdown {
            m.max_drawdown = dd;
            if peak > 0.0 {
                m.max_drawdown_pct = dd / peak * 100.0;
            }
        }
    }

    // Longest losing streak.
    let mut streak = 0usize;
    for t in trades {
        if t.pnl <= 0.0 {
            streak += 1;
            m.max_losing_streak = m.max_losing_streak.max(streak);
        } else {
            streak = 0;
        }
    }

    // Sharpe from daily equity returns, annualised by 252 trading days.
    let mut day_last: Vec<(i64, f64)> = Vec::new();
    for (i, b) in bars.iter().enumerate() {
        let day = b.ts / 86_400;
        if day_last.last().map(|(d, _)| *d) != Some(day) {
            day_last.push((day, equity_curve[i + 1]));
        } else if let Some(last) = day_last.last_mut() {
            last.1 = equity_curve[i + 1];
        }
    }
    if day_last.len() > 2 {
        let mut rets = Vec::with_capacity(day_last.len());
        for w in day_last.windows(2) {
            if w[0].1 > 0.0 {
                rets.push(w[1].1 / w[0].1 - 1.0);
            }
        }
        if rets.len() > 2 {
            let mean = rets.iter().sum::<f64>() / rets.len() as f64;
            let var = rets.iter().map(|r| (r - mean).powi(2)).sum::<f64>()
                / (rets.len() as f64 - 1.0);
            let sd = var.sqrt();
            if sd > 0.0 {
                m.sharpe = mean / sd * 252f64.sqrt();
            }
        }
    }

    let _ = halted;
    m
}
